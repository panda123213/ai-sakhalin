def derivative(func, x, h=1e-7):
    """
    Вычисляет производную функции func в точке x.
    h — маленькое приращение (чем меньше, тем точнее).
    """
    return (func(x + h) - func(x)) / h

# Пример: функция y = x^2
def f(x):
    return x**2

# Производная x^2 в точке x = 3 (по математике должно быть 6)
print(derivative(f, 3))  # Ожидаем: 6.0000002...